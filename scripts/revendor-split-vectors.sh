#!/usr/bin/env bash
# Re-vendors the SDK's shared split-signing vectors into
# cmd/realm-id/testdata/split-vectors.json (the shared SPEC §14.14 dealer vectors)
# from a COMMIT of Realm-ID/sdk, and writes cmd/realm-id/SPLIT_VECTORS_CONTRACT
# with the sha + sha256 that cmd/realm-id/dealer_test.go re-checks.
#
# Usage: revendor-split-vectors.sh <40-hex sdk commit sha>
# Reads `git -C ../sdk show <sha>:testdata/split-vectors/vectors.json` — offline, reads the
# committed blob, never the sibling working tree. A branch or HEAD is refused:
# it names no fixed content. Exit 2 = usage/environment error.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$repo_root/cmd/realm-id/testdata/split-vectors.json"
CONTRACT_OUT="$repo_root/cmd/realm-id/SPLIT_VECTORS_CONTRACT"
SDK_DIR="${SDK_DIR:-$repo_root/../sdk}"
SDK_REPO="${SDK_REPO:-Realm-ID/sdk}"
SRC_PATH="testdata/split-vectors/vectors.json"

sha256_of() {
  if command -v shasum >/dev/null 2>&1; then shasum -a 256 "$1" | awk '{print $1}';
  else sha256sum "$1" | awk '{print $1}'; fi
}

sha="${1:-}"
if ! [[ "$sha" =~ ^[0-9a-f]{40}$ ]]; then
  echo "usage: $0 <40-hex sdk commit sha>" >&2
  exit 2
fi
tmp="$(mktemp)"
if ! git -C "$SDK_DIR" show "$sha:$SRC_PATH" > "$tmp" 2>/dev/null || [ ! -s "$tmp" ]; then
  rm -f "$tmp"
  echo "::error::revendor-split-vectors: could not read $SRC_PATH at $sha in $SDK_DIR (or it is empty)." >&2
  exit 2
fi
mv "$tmp" "$OUT"
digest="$(sha256_of "$OUT")"
cat > "$CONTRACT_OUT" <<EOT
# Which sdk commit cmd/realm-id/testdata/split-vectors.json was vendored from.
# REGENERATED BY scripts/revendor-split-vectors.sh — do not hand-edit; the
# gate (cmd/realm-id/dealer_test.go) re-hashes the vendored file.
sdk_sha=$sha
sdk_repo=$SDK_REPO
source_path=$SRC_PATH
sha256=$digest
vendored_at=$(date -u +%Y-%m-%d)
EOT
echo "vendored $SDK_REPO@$sha ($SRC_PATH) sha256 $digest"
echo "  -> ${OUT#"$repo_root"/}"
echo "  -> ${CONTRACT_OUT#"$repo_root"/}"
